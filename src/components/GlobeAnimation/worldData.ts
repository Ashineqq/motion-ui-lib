/** 射线法（ray casting）判断点是否在单个多边形内部 */
function pointInPolygon(poly: Polygon, longitude: number, latitude: number): boolean {
  let inside = false;
  const n = poly.length;
  for (let i = 0, j = n - 1; i < n; j = i++) {
    const xi = poly[i][0];
    const yi = poly[i][1];
    const xj = poly[j][0];
    const yj = poly[j][1];
    // 水平射线（朝 +经度方向）与边相交测试
    const intersect =
      yi > latitude !== yj > latitude && longitude < ((xj - xi) * (latitude - yi)) / (yj - yi) + xi;
    if (intersect) inside = !inside;
  }
  return inside;
}

/** 判断经纬度是否在陆地（多个多边形并集） */
export function isLand(longitude: number, latitude: number): boolean {
  // 经度规整到 [-180, 180)
  let lng = longitude;
  while (lng >= 180) lng -= 360;
  while (lng < -180) lng += 360;
  for (const poly of LAND_POLYGONS) {
    if (pointInPolygon(poly, lng, latitude)) return true;
  }
  return false;
}

/** 按经纬度网格采样陆地散点（默认 2° 步长：点更密，适合大容器展示） */
export function generateLandPoints(stepDeg = 2): LngLat[] {
  const points: LngLat[] = [];
  const latMin = -58;
  const latMax = 74;
  for (let lat = latMin; lat <= latMax; lat += stepDeg) {
    for (let lng = -180; lng < 180; lng += stepDeg) {
      if (isLand(lng, lat)) points.push([lng, lat]);
    }
  }
  return points;
}

